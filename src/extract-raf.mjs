/**
 * extract-raf.mjs — build a runnable module out of the REAL requestAnimationFrame
 * queue section of src/vs/base/browser/dom.ts.
 *
 * The point is fidelity: the benchmark and the equivalence harness must execute the
 * actual upstream source text (byte-for-byte), not a hand-port of it. Only the module
 * scope dependencies of that section are replaced by test doubles:
 *
 *   getWindowId, onDidUnregisterWindow, markAsSingleton, onUnexpectedError
 *
 * Usage: node extract-raf.mjs <dom.ts> <variant> <out.mts>
 *
 * Variants:
 *   current        upstream, untouched
 *   sort-once      sort moved out of the drain loop (INCORRECT with mid-drain inserts)
 *   ordered-insert sort once + allocation-free ordered insertion into the current queue
 *   heap           the binary-heap proposal from microsoft/vscode#272155
 *
 * Every textual transform asserts its match count, so a silent no-op replacement is
 * impossible.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { FIX_OPS } from './fix-ops.mjs';
import { STABLE_HEAP_OPS } from './stable-heap-ops.mjs';

const [, , domTsPath, variant, outPath] = process.argv;
if (!domTsPath || !variant || !outPath) {
	console.error('usage: node extract-raf.mjs <dom.ts> <variant> <out.mts>');
	process.exit(2);
}

const source = readFileSync(domTsPath, 'utf8');
const EOL = source.includes('\r\n') ? '\r\n' : '\n';

// ---------------------------------------------------------------------------
// Slice out the animation frame section
// ---------------------------------------------------------------------------

const CLASS_START = 'class AnimationFrameQueueItem implements IDisposable {';
const IIFE_START = '(function () {';

const classIdx = source.indexOf(CLASS_START);
if (classIdx < 0) {
	throw new Error(`marker not found: ${CLASS_START}`);
}
const iifeIdx = source.indexOf(IIFE_START, classIdx);
if (iifeIdx < 0) {
	throw new Error(`marker not found: ${IIFE_START}`);
}
const IIFE_CLOSE = `${EOL}})();`;
const iifeEndIdx = source.indexOf(IIFE_CLOSE, iifeIdx);
if (iifeEndIdx < 0) {
	throw new Error('end of the animation frame IIFE not found');
}
const sectionEnd = iifeEndIdx + IIFE_CLOSE.length; // inclusive of the closing `})();`

const declaredLets = [];
for (const name of ['runAtThisOrScheduleAtNextAnimationFrame', 'scheduleAtNextAnimationFrame']) {
	const line = `export let ${name}: (targetWindow: Window, runner: () => void, priority?: number) => IDisposable;`;
	if (!source.includes(line)) {
		throw new Error(`declaration not found: ${line}`);
	}
	declaredLets.push(line);
}

const section = source.slice(classIdx, sectionEnd);
if (!section.trimEnd().endsWith('})();')) {
	throw new Error('unexpected section tail: ' + JSON.stringify(section.slice(-80)));
}

// ---------------------------------------------------------------------------
// Test doubles (the only non-upstream text in the generated module)
// ---------------------------------------------------------------------------

const header = `/* eslint-disable */
// AUTO-GENERATED by extract-raf.mjs from ${domTsPath}
// variant: ${variant}
// The animation frame section below is copied verbatim from VS Code's
// src/vs/base/browser/dom.ts; only the module-scope dependencies are stubbed.

type IDisposable = { dispose(): void };

const __windowIds = new WeakMap<object, number>();
let __nextWindowId = 0;
export function __getWindowId(targetWindow: object): number {
	let id = __windowIds.get(targetWindow);
	if (id === undefined) {
		id = ++__nextWindowId;
		__windowIds.set(targetWindow, id);
	}
	return id;
}
const __unregisterCallbacks: Array<(e: { vscodeWindowId: number }) => void> = [];
export function __fireWindowUnregister(vscodeWindowId: number): void {
	for (const cb of __unregisterCallbacks) {
		cb({ vscodeWindowId });
	}
}
export const __unexpectedErrors: unknown[] = [];

function getWindowId(targetWindow: object): number { return __getWindowId(targetWindow); }
function onDidUnregisterWindow(cb: (e: { vscodeWindowId: number }) => void): IDisposable {
	__unregisterCallbacks.push(cb);
	return { dispose() { /* noop */ } };
}
function markAsSingleton<T>(value: T): T { return value; }
function onUnexpectedError(error: unknown): void { __unexpectedErrors.push(error); }

export type { IDisposable };
`;

// ---------------------------------------------------------------------------
// Variant transforms. Each op asserts its match count so a wrong anchor fails loudly.
// ---------------------------------------------------------------------------

const T = '\t';

function op(find, replace, count = 1) {
	return { find, replace, count };
}

const LOOP_BODY = [
	`${T}${T}while (currentQueue.length > 0) {`,
	`${T}${T}${T}currentQueue.sort(AnimationFrameQueueItem.sort);`,
	`${T}${T}${T}const top = currentQueue.shift()!;`,
	`${T}${T}${T}top.execute();`,
	`${T}${T}}`,
	'',
].join('\n');

const helpDocs = `document.execCommand ? '' : ''`;

const insertSortedHelper = [
	`${T}/**`,
	`${T} * Inserts an item into a queue that is sorted by priority (descending), keeping the`,
	`${T} * queue ordered. Items with an equal priority are placed after the ones already in`,
	`${T} * the queue, which is the order a stable ${'`Array#sort`'} of the whole queue produced`,
	`${T} * before. Index moves only: no array is allocated and nothing is returned.`,
	`${T} */`,
	`${T}function insertSorted(queue: AnimationFrameQueueItem[], item: AnimationFrameQueueItem): void {`,
	`${T}${T}let low = 0;`,
	`${T}${T}let high = queue.length;`,
	`${T}${T}while (low < high) {`,
	`${T}${T}${T}const mid = (low + high) >>> 1;`,
	`${T}${T}${T}if (queue[mid].priority >= item.priority) {`,
	`${T}${T}${T}${T}low = mid + 1;`,
	`${T}${T}${T}} else {`,
	`${T}${T}${T}${T}high = mid;`,
	`${T}${T}${T}}`,
	`${T}${T}}`,
	`${T}${T}queue.push(item);`,
	`${T}${T}if (low < queue.length - 1) {`,
	`${T}${T}${T}queue.copyWithin(low + 1, low, queue.length - 1);`,
	`${T}${T}${T}queue[low] = item;`,
	`${T}${T}}`,
	`${T}}`,
	'',
	`${T}const animationFrameRunner = (targetWindowId: number) => {`,
].join('\n');

const heapHelper = [
	`${T}/**`,
	`${T} * BinaryHeap as proposed in microsoft/vscode#272155: descending priority, ties`,
	`${T} * resolved arbitrarily (an unstable order, as heaps are).`,
	`${T} */`,
	`${T}class AnimationFrameHeap {`,
	`${T}${T}private _items: AnimationFrameQueueItem[] = [];`,
	`${T}${T}get length(): number { return this._items.length; }`,
	`${T}${T}clear(): void { this._items.length = 0; }`,
	`${T}${T}push(item: AnimationFrameQueueItem): void {`,
	`${T}${T}${T}this._items.push(item);`,
	`${T}${T}${T}this._bubbleUp(this._items.length - 1);`,
	`${T}${T}}`,
	`${T}${T}shift(): AnimationFrameQueueItem | undefined {`,
	`${T}${T}${T}if (this._items.length === 0) { return undefined; }`,
	`${T}${T}${T}if (this._items.length === 1) { return this._items.pop()!; }`,
	`${T}${T}${T}const result = this._items[0];`,
	`${T}${T}${T}this._items[0] = this._items.pop()!;`,
	`${T}${T}${T}this._bubbleDown(0);`,
	`${T}${T}${T}return result;`,
	`${T}${T}}`,
	`${T}${T}private _bubbleUp(index: number): void {`,
	`${T}${T}${T}const item = this._items[index];`,
	`${T}${T}${T}while (index > 0) {`,
	`${T}${T}${T}${T}const parentIndex = (index - 1) >>> 1;`,
	`${T}${T}${T}${T}const parent = this._items[parentIndex];`,
	`${T}${T}${T}${T}if (item.priority <= parent.priority) { break; }`,
	`${T}${T}${T}${T}this._items[index] = parent;`,
	`${T}${T}${T}${T}index = parentIndex;`,
	`${T}${T}${T}}`,
	`${T}${T}${T}this._items[index] = item;`,
	`${T}${T}}`,
	`${T}${T}private _bubbleDown(index: number): void {`,
	`${T}${T}${T}const length = this._items.length;`,
	`${T}${T}${T}const item = this._items[index];`,
	`${T}${T}${T}while (true) {`,
	`${T}${T}${T}${T}let maxIndex = index;`,
	`${T}${T}${T}${T}let maxPriority = item.priority;`,
	`${T}${T}${T}${T}const left = 2 * index + 1;`,
	`${T}${T}${T}${T}const right = 2 * index + 2;`,
	`${T}${T}${T}${T}if (left < length && this._items[left].priority > maxPriority) {`,
	`${T}${T}${T}${T}${T}maxIndex = left;`,
	`${T}${T}${T}${T}${T}maxPriority = this._items[left].priority;`,
	`${T}${T}${T}${T}}`,
	`${T}${T}${T}${T}if (right < length && this._items[right].priority > maxPriority) {`,
	`${T}${T}${T}${T}${T}maxIndex = right;`,
	`${T}${T}${T}${T}}`,
	`${T}${T}${T}${T}if (maxIndex === index) { break; }`,
	`${T}${T}${T}${T}this._items[index] = this._items[maxIndex];`,
	`${T}${T}${T}${T}index = maxIndex;`,
	`${T}${T}${T}}`,
	`${T}${T}${T}this._items[index] = item;`,
	`${T}${T}}`,
	`${T}}`,
	'',
	`${T}const animationFrameRunner = (targetWindowId: number) => {`,
].join('\n');

void helpDocs;

const variants = {
	current: [],

	'sort-once': [
		op(LOOP_BODY, `${T}${T}currentQueue.sort(AnimationFrameQueueItem.sort);\n${T}${T}while (currentQueue.length > 0) {\n${T}${T}${T}const top = currentQueue.shift()!;\n${T}${T}${T}top.execute();\n${T}${T}}\n`),
	],

	'ordered-insert': FIX_OPS,

	'mutant-gt': [...FIX_OPS, op(`${T}${T}${T}if (queue[mid].priority >= item.priority) {`, `${T}${T}${T}if (queue[mid].priority > item.priority) {`)],

	'stable-heap': STABLE_HEAP_OPS,

	heap: [
		op(`${T}const animationFrameRunner = (targetWindowId: number) => {`, heapHelper),
		op(`${T}const NEXT_QUEUE = new Map<number /* window ID */, AnimationFrameQueueItem[]>();`, `${T}const NEXT_QUEUE = new Map<number /* window ID */, AnimationFrameHeap>();`),
		op(`${T}const CURRENT_QUEUE = new Map<number /* window ID */, AnimationFrameQueueItem[]>();`, `${T}const CURRENT_QUEUE = new Map<number /* window ID */, AnimationFrameHeap>();`),
		op(`${T}${T}if (currentQueue) {\n${T}${T}${T}currentQueue.length = 0;\n${T}${T}}`, `${T}${T}if (currentQueue) {\n${T}${T}${T}currentQueue.clear();\n${T}${T}}`),
		op(`${T}${T}const currentQueue = NEXT_QUEUE.get(targetWindowId) ?? [];`, `${T}${T}const currentQueue = NEXT_QUEUE.get(targetWindowId) ?? new AnimationFrameHeap();`),
		op(`${T}${T}NEXT_QUEUE.set(targetWindowId, []);`, `${T}${T}NEXT_QUEUE.set(targetWindowId, new AnimationFrameHeap());`),
		op(`${T}${T}${T}nextQueue = [];`, `${T}${T}${T}nextQueue = new AnimationFrameHeap();`),
		op(LOOP_BODY, `${T}${T}while (currentQueue.length > 0) {\n${T}${T}${T}const top = currentQueue.shift()!;\n${T}${T}${T}top.execute();\n${T}${T}}\n`),
		op(`${T}${T}${T}currentQueue = [];`, `${T}${T}${T}currentQueue = new AnimationFrameHeap();`),
	],
};

const ops = variants[variant];
if (!ops) {
	throw new Error(`unknown variant ${variant}; known: ${Object.keys(variants).join(', ')}`);
}

let transformed = section;
const report = [];
for (const { find, replace, count } of ops) {
	const hits = transformed.split(find).length - 1;
	if (hits !== count) {
		throw new Error(`transform anchor matched ${hits} times, expected ${count}:\n---\n${find}\n---`);
	}
	transformed = transformed.replaceAll(find, replace);
	report.push(`${count}x ${JSON.stringify(find.split('\n')[0].trim().slice(0, 70))}`);
}

const out = `${header}\n${declaredLets.join('\n')}\n\n${transformed}\n`;
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (variant ${variant}, ${out.split('\n').length} lines)`);
for (const r of report) {
	console.log('  transform:', r);
}
